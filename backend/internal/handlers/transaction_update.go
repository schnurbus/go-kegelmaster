// updateTransactionRequest carries the complete new state of a manual
// booking. Unlike creation there is no auto-tip split and no couples mode:
// the booking is stored exactly as entered.
type updateTransactionRequest struct {
	TransactionType string  `json:"transaction_type"`
	PlayerID        *string `json:"player_id,omitempty"`
	Amount          int     `json:"amount"`
	Description     string  `json:"description,omitempty"`
	TransactionDate *string `json:"transaction_date,omitempty"` // YYYY-MM-DD, optional (keeps the date)
}

func (r updateTransactionRequest) toParams(clubID string) (transaction.UpdateTransactionParams, error) {
	txType := transaction.TransactionType(r.TransactionType)
	if !txType.IsValid() {
		return transaction.UpdateTransactionParams{}, errors.New("Ungültiger Transaktionstyp")
	}
	if !txType.IsManual() {
		return transaction.UpdateTransactionParams{}, errors.New("Nur Einzahlung, Trinkgeld oder Ausgabe sind möglich")
	}
	if r.Amount <= 0 {
		return transaction.UpdateTransactionParams{}, errors.New("Betrag muss positiv sein")
	}
	if r.Amount > transaction.MaxAmount {
		return transaction.UpdateTransactionParams{}, errors.New("Betrag ist zu hoch")
	}
	playerID := r.PlayerID
	if playerID != nil && strings.TrimSpace(*playerID) == "" {
		playerID = nil
	}
	if txType != transaction.TransactionTypeExpense && playerID == nil {
		return transaction.UpdateTransactionParams{}, errors.New("Einzahlungen und Trinkgeld benötigen einen Spieler")
	}
	params := transaction.UpdateTransactionParams{
		ClubID:          clubID,
		PlayerID:        playerID,
		TransactionType: txType,
		Amount:          r.Amount,
		Description:     strings.TrimSpace(r.Description),
	}
	if txType == transaction.TransactionTypeExpense {
		params.Amount = -r.Amount
	}
	if r.TransactionDate != nil && strings.TrimSpace(*r.TransactionDate) != "" {
		parsed, err := time.Parse("2006-01-02", strings.TrimSpace(*r.TransactionDate))
		if err != nil {
			return transaction.UpdateTransactionParams{}, errors.New("Transaktionsdatum muss im Format YYYY-MM-DD sein")
		}
		params.TransactionDate = time.Date(parsed.Year(), parsed.Month(), parsed.Day(), 12, 0, 0, 0, time.UTC)
	}
	return params, nil
}

// HandleUpdateTransaction edits a manual transaction (deposit, tip, expense).
// Player and club balances are corrected in the same database transaction.
// Bookings generated by a game day (base fee, penalty fee) are rejected.
func (h *Handler) HandleUpdateTransaction(c fiber.Ctx) error {
	if err := h.ValidateCSRF(c); err != nil {
		return err
	}

	ctx, cancel := h.RequestContext()
	defer cancel()

	u, err := h.UserFromCookie(ctx, c)
	if err != nil {
		return fiber.NewError(fiber.StatusUnauthorized, "Nicht angemeldet")
	}

	clubID := c.Params("clubId")
	txID := c.Params("id")
	if clubID == "" || txID == "" {
		return fiber.NewError(fiber.StatusBadRequest, "Club-ID und Transaction-ID sind erforderlich")
	}

	hasPermission, err := h.PermissionChecker.HasPermission(ctx, u.ID, clubID, role.EntityTypeTransactions, role.PermissionTypeUpdate)
	if err != nil {
		if errors.Is(err, club.ErrNotFound) {
			return fiber.NewError(fiber.StatusNotFound, "Club nicht gefunden")
		}
		slog.Error("permission check failed", "error", err)
		return fiber.NewError(fiber.StatusInternalServerError, "Interner Fehler")
	}
	if !hasPermission {
		return fiber.NewError(fiber.StatusForbidden, "Keine Berechtigung")
	}

	var req updateTransactionRequest
	if err := json.Unmarshal(c.Body(), &req); err != nil {
		return fiber.NewError(fiber.StatusBadRequest, "Ungültige Anfrage")
	}
	params, err := req.toParams(clubID)
	if err != nil {
		return fiber.NewError(fiber.StatusBadRequest, err.Error())
	}

	updated, err := h.TransactionRepo.Update(ctx, txID, params)
	if err != nil {
		switch {
		case errors.Is(err, transaction.ErrNotFound):
			return fiber.NewError(fiber.StatusNotFound, "Transaktion nicht gefunden")
		case errors.Is(err, transaction.ErrNotEditable):
			return fiber.NewError(fiber.StatusBadRequest, "Grund- und Strafgebühren können nicht bearbeitet werden. Bitte korrigieren Sie sie im Spieltag.")
		case errors.Is(err, transaction.ErrPlayerNotInClub), errors.Is(err, player.ErrNotFound):
			return fiber.NewError(fiber.StatusBadRequest, "Spieler gehört nicht zu diesem Klub")
		case errors.Is(err, transaction.ErrPlayerRequired):
			return fiber.NewError(fiber.StatusBadRequest, "Einzahlungen und Trinkgeld benötigen einen Spieler")
		case errors.Is(err, transaction.ErrInvalidAmount), errors.Is(err, transaction.ErrInvalidType):
			return fiber.NewError(fiber.StatusBadRequest, "Ungültiger Betrag oder Transaktionstyp")
		case errors.Is(err, club.ErrNotFound):
			return fiber.NewError(fiber.StatusNotFound, "Club nicht gefunden")
		}
		slog.Error("update transaction", "error", err)
		return fiber.NewError(fiber.StatusInternalServerError, "Fehler beim Bearbeiten der Transaktion")
	}

	audit.LogAudit(c, u.ID, audit.ActionTransactionUpdated, "club_id", clubID, "transaction_id", txID)
	return c.JSON(TransactionResponseFromEntity(*updated))
}
